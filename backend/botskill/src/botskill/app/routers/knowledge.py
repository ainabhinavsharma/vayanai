class CreateRuleRequest(BaseModel):
    title: str
    rule_type: str = "MANDATORY_POLICY"
    severity: str = "HIGH"
    condition: str
    required_action: str
    prohibited_actions: List[str] = []
    source_document_id: Optional[str] = "doc_vayanai_custom_policy"
    source_location: Optional[str] = "Supervision Desk"
    source_quote: Optional[str] = ""
    is_active: bool = True


@router.post("/rules", response_model=RuleResponse, summary="Add a new company policy or operational guardrail rule")
async def create_rule(req: CreateRuleRequest, request: Request):
    db_mgr = getattr(request.app.state, "db_manager", None)
    if not db_mgr:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Database manager not initialized.",
        )

    import re as py_re
    try:
        r_type = RuleType(req.rule_type)
    except Exception:
        r_type = RuleType.MANDATORY_POLICY

    try:
        r_sev = SeverityLevel(req.severity)
    except Exception:
        r_sev = SeverityLevel.HIGH

    now = datetime.now(timezone.utc).isoformat()
    clean_title = py_re.sub(r"[^A-Za-z0-9]+", "-", req.title.upper()).strip("-")[:12]
    rule_id = f"RULE-{clean_title}-{uuid.uuid4().hex[:4].upper()}"

    rule = PolicyRule(
        rule_id=rule_id,
        title=req.title.strip(),
        rule_type=r_type,
        severity=r_sev,
        condition=req.condition.strip(),
        required_action=req.required_action.strip(),
        prohibited_actions=req.prohibited_actions,
        source_document_id=req.source_document_id or "doc_vayanai_custom_policy",
        source_location=req.source_location or "Supervision Desk",
        source_quote=req.source_quote or req.required_action.strip(),
        is_active=req.is_active,
        created_at=now,
    )

    repo = db_mgr.get_repository()
    repo.insert_rule(rule)

    audit = AuditEvent(
        event_id=f"audit_rule_create_{int(time.time() * 1000)}_{uuid.uuid4().hex[:6]}",
        timestamp=now,
        event_type="POLICY_RULE_CREATED",
        severity=SeverityLevel.LOW,
        details={"rule_id": rule_id, "title": rule.title},
    )
    repo.log_audit(audit)

    return RuleResponse(
        rule_id=rule.rule_id,
        title=rule.title,
        rule_type=rule.rule_type.value,
        severity=rule.severity.value,
        condition=rule.condition,
        required_action=rule.required_action,
        prohibited_actions=rule.prohibited_actions,
        source_document_id=rule.source_document_id,
        source_location=rule.source_location,
        source_quote=rule.source_quote,
        is_active=rule.is_active,
        created_at=rule.created_at,
    )
